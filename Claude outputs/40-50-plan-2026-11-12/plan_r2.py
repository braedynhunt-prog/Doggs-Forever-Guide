"""Build the round-2 route file and the generated sections of the route plan from the pool and the verdicts.
Usage: python plan_r2.py <repo root> <pool dir> <route out> <markdown out>
The route file is what tooling/route_xp.py reads; the markdown holds the XP table, the per-chapter lists and the out lists."""
import sys, os, re, json, collections
ROOT, PD, ROUTE, MD = sys.argv[1:5]
sys.path.insert(0, os.path.join(ROOT, 'tooling'))
import route_xp as rx
P = {int(k): v for k, v in json.load(open(os.path.join(PD, '_pool.json'), encoding='utf-8')).items()}
V = {}
for l in open(os.path.join(PD, '_decisions.tsv'), encoding='utf-8'):
    r = l.rstrip(chr(10)).split(chr(9)); V[int(r[1])] = (r[7], r[8], r[11] if len(r) > 11 else '')
for q in P.values(): q['v'], q['why'], q['best'] = V[q['id']]; q['cat'] = str(q['cat'])
REQ = ('PLAIN', 'LINK', 'DUN-normal', 'DUN-boss')
OPT = ('DUN-grind', 'GROUP-OPT', 'COND', 'ASK', 'GATE')
FRIZ_STV, FRIZ_TAN, FRIZ_BACK = {95295, 95322, 95325}, {95296, 95383, 95312, 95321}, {95327, 95472, 97332}
SW = {94894, 94893, 1448, 1363, 1477, 1395}
AERIE = {1449, 1450, 1451}
ULDUM_OUT, ULDUM_BACK = {2963, 2946, 2954}, {2977, 2964}
TYMOR_OUT, TYMOR_BACK = {3448, 3449, 3450, 3451}, {3461}
ELSE = FRIZ_STV | FRIZ_TAN | FRIZ_BACK | SW | AERIE | ULDUM_OUT | ULDUM_BACK | TYMOR_OUT | TYMOR_BACK | {95219, 2769, 3520}
c = lambda q, cat: q['cat'] == cat and q['id'] not in ELSE
EXTRA = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'chapters_r2.json'), encoding='utf-8'))
SEL = {
 '42': lambda q: c(q, '16591') or (q['cat'] == '16842' and not q['v'].startswith('DUN') and q['v'] != 'COND'),
 '43': lambda q: q['cat'] == '16842',
 '44': lambda q: c(q, '3') or c(q, '38') or q['id'] in AERIE,
 '45': lambda q: q['id'] in SW | FRIZ_STV or (c(q, '33') and q['lv'] <= 42) or (c(q, '1519') and q['lv'] <= 45) or c(q, '10'),
 '46': lambda q: q['id'] in FRIZ_TAN or (c(q, '440') and q['lv'] <= 46),
 '48': lambda q: q['cat'] == '1176' or q['id'] in (2769, 3520),
 '47': lambda q: q['id'] == 95219 or (c(q, '357') and q['lv'] <= 45),
 '49': lambda q: q['id'] in FRIZ_BACK or c(q, '47') or q['id'] in ULDUM_OUT - {2946, 2954} or q['id'] in {3448, 3450, 3451},
 '50': lambda q: c(q, '51'),
 '51': lambda q: c(q, '33') and q['lv'] >= 43,
 '52': lambda q: c(q, '357') and q['lv'] >= 46,
 '53': lambda q: q['cat'] == '2100',
 '54': lambda q: q['id'] in {2946, 2954} or (c(q, '440') and q['lv'] >= 47 and q['rq'] <= 48),
 '55': lambda q: q['id'] in (3449, 5141) or c(q, '16'),
 '56': lambda q: c(q, '490'),
 '57': lambda q: q['id'] in ULDUM_BACK | TYMOR_BACK,
}
W = rx.load_quests()
used, chapters = set(), []
for ch in EXTRA['chapters']:
    sel = SEL[ch['n']]
    qs = [q for q in P.values() if q['id'] not in used and sel(q) and q['v'] in REQ + OPT and q['id'] not in set(ch.get('drop', []))]
    used |= {q['id'] for q in qs}
    key = lambda q: (q['rq'], q['lv'], q['id'])
    chapters.append(dict(ch, req=sorted([q for q in qs if q['v'] in REQ], key=key), opt=sorted([q for q in qs if q['v'] in OPT], key=key)))
unplaced = [q for q in P.values() if q['id'] not in used and q['v'] in REQ + OPT]
# ---- route file
lines = ['# Round 2 (levels 42-50) of the 30-60 guide: required quests per chapter, 12 Nov 2026.', '# python tooling/route_xp.py docs/40-50-route-2026-11-12.txt', 'start 42.0', 'share 0.65']
for ch in chapters:
    lines.append(f"== {ch['n']} {ch['title']} | wants {ch['wants']}")
    if ch['req']: lines.append(' '.join(str(q['id']) for q in ch['req']))
    if ch['opt']: lines.append('opt: ' + ' '.join(str(q['id']) for q in ch['opt']))
open(ROUTE, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
# ---- XP table (same arithmetic as route_xp.py)
level, cum, cum_money = 42.0, 0, 0
out = ['| ch | chapter | wants | required quests | quest XP | money | level in | level out | highest required level | optional XP |', '|---|---|---|---|---|---|---|---|---|---|']
for ch in chapters:
    xp = sum(round((W.get(q['id'], {}).get('xp') or 0) * rx.scale(int(level), W.get(q['id'], {}).get('level') or 0)) for q in ch['req'])
    mon = sum(q['money'] for q in ch['req']); oxp = sum(q['xp'] for q in ch['opt'])
    entry = level; level = rx.add_xp(level, xp / 0.65); cum += xp; cum_money += mon
    ch['entry'], ch['exit'], ch['xp'], ch['oxp'], ch['mon'] = entry, level, xp, oxp, mon
    mr = max([q['rq'] for q in ch['req']] or [0])
    out.append(f"| {ch['n']} | {ch['title']} | {ch['wants']} | {len(ch['req'])} | {xp:,} | {rx.money(mon)} | {entry:.1f} | {level:.1f} | {mr} | {oxp:,} |")
out.append(f"| | **total** | | {sum(len(ch['req']) for ch in chapters)} | **{cum:,}** | {rx.money(cum_money)} | 42.0 | **{level:.1f}** | | {sum(ch['oxp'] for ch in chapters):,} |")
md = ['<!-- generated by plan_r2.py from the pool and the verdicts; do not edit by hand -->', '', '## XP table', ''] + out + ['']
# ---- chapters
LBL = {'DUN-normal': 'normal', 'DUN-boss': 'normal (boss item, one kill)', 'DUN-grind': 'grind / luck', 'GROUP-OPT': 'GROUP, optional', 'COND': 'conditional', 'ASK': 'your call', 'GATE': 'gate', 'LINK': 'chain step'}
def ql(q, why=False):
    s = f"{q['id']} {q['name']} (L{q['lv']}, req {q['rq']}) {q['xp']:,}"
    if q['v'] in LBL: s += f" [{LBL[q['v']]}]"
    if why and q['why']: s += f" - {q['why']}"
    elif q['v'] == 'PLAIN' and q['why'] and '%' in q['why']: s += f" - {q['why']}"
    if q['maxlv'] and q['v'] in REQ: s += f" [mobs to {q['maxlv']}]"
    return s
md += ['## Chapters', '']
for ch in chapters:
    md += [f"### {ch['n']} {ch['title']}", '',
           f"File `{ch['file']}`, title `[N {int(ch['entry'])}-{max(int(ch['entry']) + 1, int(ch['exit'] + 0.999))} {ch['short']}]`. Wants level **{ch['wants']}**; predicted {ch['entry']:.1f} -> {ch['exit']:.1f}. {len(ch['req'])} required quests, {ch['xp']:,} XP, {rx.money(ch['mon'])}; optional {ch['oxp']:,} XP.", '',
           ch['note'], '']
    if ch['req']: md += ['**Required:**'] + [f"- {ql(q)}" for q in ch['req']] + ['']
    if ch['opt']: md += ['**Optional / conditional:**'] + [f"- {ql(q, True)}" for q in ch['opt']] + ['']
    mobs = [q['maxlv'] for q in ch['req'] if q['maxlv']]
    under = [q for q in ch['req'] if q['rq'] > int(ch['entry'])]
    if under: md += [f"Level check: {', '.join(str(q['id']) + ' needs ' + str(q['rq']) for q in under)}; predicted entry {ch['entry']:.1f}.", '']
# ---- scored rewards
md += ['## Best scored reward per kept quest (2H Enhancement, level-40 band; mail counts from 40)', '',
       'The best usable reward of each kept quest, top five per slot. The specs turn these into gear calls against what he wears by then.', '',
       '| slot | score | item | quest | chapter |', '|---|---|---|---|---|']
slots = collections.defaultdict(list)
for ch in chapters:
    for q in ch['req'] + ch['opt']:
        m = re.match(r'(\S+(?: \S+)?) ([\d.]+) (.*)', q['best'] or '')
        if m and float(m.group(2)) > 0: slots[m.group(1)].append((float(m.group(2)), m.group(3), q, ch['n']))
for slot in sorted(slots):
    for sc, item, q, n in sorted(slots[slot], key=lambda x: -x[0])[:5]:
        md.append(f"| {slot} | {sc} | {item} | {q['id']} {q['name']}{' [' + LBL[q['v']] + ']' if q['v'] in LBL else ''} | {n} |")
md.append('')
# ---- out lists
md += ['## Out, by zone (silent in the guide; the reason is recorded here)', '', 'Round-2 zones only; quests below the bracket that were only looked at as prerequisites are not listed. The full verdict file is `Claude outputs/40-50-plan-2026-11-12/_decisions.tsv`.', '']
ZN = EXTRA['zones']
R2CATS = {'16591', '16842', '33', '357', '440', '51', '47', '490', '16', '3', '2100', '1176', '405', '45', '4', '1519', '1537', '1337', '40', '15', '38', '-182', '10'}
bycat = collections.defaultdict(lambda: collections.defaultdict(list))
for q in P.values():
    if q['v'] in ('OUT', 'JUDGE-OUT') and q['cat'] in R2CATS and 'PRECHAIN' not in q['flags']:
        why = re.sub(r'chain behind (\d+) ([^(]+) \(.*', r'chain behind \1 \2', q['why']).strip()
        bycat[q['cat']][('judgment: ' if q['v'] == 'JUDGE-OUT' else '') + why].append(q)
for cat in sorted(bycat, key=lambda k: -sum(q['xp'] for v in bycat[k].values() for q in v)):
    tot = sum(q['xp'] for v in bycat[cat].values() for q in v)
    md.append(f"**{ZN.get(cat, 'category ' + cat)}** ({sum(len(v) for v in bycat[cat].values())} quests, {tot:,} XP)")
    for why, qs in sorted(bycat[cat].items(), key=lambda kv: -sum(q['xp'] for q in kv[1])):
        md.append(f"- {why}: " + '; '.join(f"{q['id']} {q['name']} ({q['xp']:,})" for q in sorted(qs, key=lambda q: q['id'])))
    md.append('')
md += ['## Left for round 3 (in the pool, not used here)', '']
later = collections.defaultdict(list)
for q in P.values():
    if q['v'] == 'LATER': later[q['why']].append(q)
for why, qs in sorted(later.items()): md.append(f"- {why}: " + '; '.join(f"{q['id']} {q['name']} ({q['xp']:,})" for q in sorted(qs, key=lambda q: q['id'])))
if unplaced:
    md += ['', '## In the pool, kept by the rules, not used in round 2 (round 3 starts from these)', '']
    un = collections.defaultdict(list)
    for q in unplaced: un[q['cat']].append(q)
    for cat, qs in sorted(un.items(), key=lambda kv: -sum(q['xp'] for q in kv[1])):
        md.append(f"- {ZN.get(cat, 'category ' + cat)}: {len(qs)} quests, {sum(q['xp'] for q in qs):,} XP (quest levels {min(q['lv'] for q in qs)}-{max(q['lv'] for q in qs)})")
open(MD, 'w', encoding='utf-8', newline='\n').write('\n'.join(md) + '\n')
print('\n'.join(out))
print('unplaced', len(unplaced), sum(q['xp'] for q in unplaced), '|', collections.Counter(q['cat'] for q in unplaced).most_common(12))
